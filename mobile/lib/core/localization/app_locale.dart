import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// Global LocaleProvider managing language selection, persistence, and reactive updates.
class LocaleProvider extends ChangeNotifier {
  static const String prefKey = 'selected_language';
  static const List<Locale> supportedLocales = [
    Locale('en'),
    Locale('ta'),
    Locale('hi'),
  ];

  String _currentLanguage = 'en';

  String get currentLanguage => _currentLanguage;
  Locale get locale => Locale(_currentLanguage);

  LocaleProvider() {
    _loadSavedLanguage();
  }

  Future<void> _loadSavedLanguage() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final saved = prefs.getString(prefKey);
      if (saved != null && (saved == 'en' || saved == 'ta' || saved == 'hi')) {
        _currentLanguage = saved;
        notifyListeners();
      }
    } catch (_) {}
  }

  Future<void> setLanguage(String langCode) async {
    if (langCode != 'en' && langCode != 'ta' && langCode != 'hi') return;
    if (_currentLanguage != langCode) {
      _currentLanguage = langCode;
      try {
        final prefs = await SharedPreferences.getInstance();
        await prefs.setString(prefKey, langCode);
      } catch (_) {}
      notifyListeners();
    }
  }

  void setLocale(Locale loc) {
    setLanguage(loc.languageCode);
  }

  static String formatFallbackKey(String key) {
    if (!key.contains('_')) {
      if (key.isEmpty) return key;
      return key[0].toUpperCase() + key.substring(1);
    }
    return key
        .split('_')
        .where((word) => word.isNotEmpty)
        .map((word) => word[0].toUpperCase() + word.substring(1).toLowerCase())
        .join(' ');
  }

  String translate(String key, [Map<String, dynamic>? params]) {
    String text = _localizedValues[_currentLanguage]?[key] ??
        _localizedValues['en']?[key] ??
        formatFallbackKey(key);
    if (params != null && params.isNotEmpty) {
      params.forEach((k, v) {
        text = text.replaceAll('{$k}', v.toString());
      });
    }
    return text;
  }

