/// Reactive Extension on BuildContext for quick and reliable localization in any widget
extension AppLocaleExt on BuildContext {
  String tr(String key, [Map<String, dynamic>? params]) {
    try {
      final provider = Provider.of<LocaleProvider>(this, listen: false);
      return provider.translate(key, params);
    } catch (_) {
      return key;
    }
  }

  LocaleProvider get localeProvider =>
      Provider.of<LocaleProvider>(this, listen: false);

  String trCategory(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getFoodCategory(raw);

  String trFood(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getFoodItem(raw);

  String trStorage(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getStorageMethod(raw);

  String trPackaging(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getPackagingCondition(raw);

  String trUrgency(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getUrgency(raw);

  String trStatus(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getStatus(raw);

  String trVisual(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getVisualCondition(raw);

  String trFeasibility(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getFeasibility(raw);

  String trUnit(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getUnit(raw);

  String trRole(String raw) =>
      Provider.of<LocaleProvider>(this, listen: false).getRole(raw);

  String trRemainingMinutes(int minutes) =>
      Provider.of<LocaleProvider>(this, listen: false)
          .getRemainingMinutesText(minutes);

  String trMealsCount(num count) =>
      Provider.of<LocaleProvider>(this, listen: false).getMealsCountText(count);

  String trOtpDonor(String otp) =>
      Provider.of<LocaleProvider>(this, listen: false).getOtpInstructionDonor(otp);

  String trOtpVolunteer() =>
      Provider.of<LocaleProvider>(this, listen: false).getOtpInstructionVolunteer();

  String trDisclaimer() =>
      Provider.of<LocaleProvider>(this, listen: false).getSafetyDisclaimer();

  String trError(String errorMsg) =>
      Provider.of<LocaleProvider>(this, listen: false).getErrorMessage(errorMsg);
}
