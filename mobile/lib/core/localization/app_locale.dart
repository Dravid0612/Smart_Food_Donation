  String getSafetyDisclaimer() {
    return translate('safety_disclaimer');
  }

  String getErrorMessage(String errorKeyOrDetail) {
    final lower = errorKeyOrDetail.toLowerCase();
    if (lower.contains('timeout')) return translate('err_timeout');
    if (lower.contains('network') || lower.contains('connection')) return translate('err_network');
    if (lower.contains('unauthorized') || lower.contains('401')) return translate('err_unauthorized');
    if (lower.contains('permission') || lower.contains('403') || lower.contains('forbidden')) return translate('err_forbidden');
    if (lower.contains('not found') || lower.contains('404')) return translate('err_not_found');
    if (lower.contains('already been accepted') || lower.contains('conflict') || lower.contains('409')) return translate('err_conflict');
    if (lower.contains('validation') || lower.contains('422')) return translate('err_validation');
    if (lower.contains('invalid otp')) return translate('err_invalid_otp');
    if (lower.contains('otp has expired')) return translate('err_expired_otp');
    if (lower.contains('already used') || lower.contains('consumed')) return translate('err_otp_used');
    if (lower.contains('server error') || lower.contains('500')) return translate('err_server');
    return errorKeyOrDetail;
  }

